/** Build a seller offer for a product (multi-seller rollup helper). */
function seller(
  id: string,
  name: string,
  price: number,
  opts: Partial<Seller> = {}
): Seller {
  return {
    id,
    name,
    providerId: `p-${id}`,
    logo: `https://picsum.photos/seed/${id}/80/80`,
    rating: opts.rating ?? 4.3,
    ratingCount: opts.ratingCount ?? 1200,
    etaMinMins: opts.etaMinMins ?? 30,
    etaMaxMins: opts.etaMaxMins ?? 45,
    price,
    mrp: opts.mrp,
    deliveryFee: opts.deliveryFee ?? 25,
    freeDeliveryAbove: opts.freeDeliveryAbove ?? 499,
    distanceKm: opts.distanceKm ?? 2.4,
    ...opts,
  };
}

function img(seed: string, n = 3): string[] {
  return Array.from({ length: n }, (_, i) => `https://picsum.photos/seed/${seed}-${i}/800/800`);
}

